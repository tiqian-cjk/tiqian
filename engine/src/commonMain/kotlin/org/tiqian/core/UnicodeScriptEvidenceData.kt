        var low = 0
        var high = (UnicodeScriptEvidenceData.RANGES.size / 3) - 1
        while ((low <= high)) {
            val middle = ((low + high) shr (1))
            val base = middle * 3
            val start = UnicodeScriptEvidenceData.RANGES[base]
            val end = UnicodeScriptEvidenceData.RANGES[base + 1]
            if ((codePoint < start)) {
                high = middle - 1
            } else {
                if ((codePoint > end)) {
                    low = middle + 1
                } else {
                    if ((UnicodeScriptEvidenceData.RANGES[base + 2] == 1)) {
                        return UnicodeScriptEvidence.EastAsian
                    } else {
                        return UnicodeScriptEvidence.Other
                    }
                }
            }
        }
        return UnicodeScriptEvidence.Neutral
    }
