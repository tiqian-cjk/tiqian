/// True when `point` falls inside one of the table's ranges.
pub fn table_contains(table: &[(u32, u32)], point: u32) -> bool {
    table
        .binary_search_by(|&(low, high)| {
            if point < low {
                std::cmp::Ordering::Greater
            } else if point > high {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
